"""End-to-end reproduction pipeline for
"Actionability-Aware Reward Modelling and Sensitivity Analysis for
Real-Time Sales-Funnel Optimisation".

Every number in the manuscript's tables should be regenerated by this script
from the two public datasets and config.json. Nothing is read back from the
paper.

Usage:
    python run_pipeline.py --smartconvert training_sample.csv \
                           --balabit Mouse-Dynamics-Challenge/training_files \
                           --out results

Stages
  1. Checkout scoping and feature lift audit (all columns, not only retained ones)
  2. Reward prior: holdout discrimination with bootstrap CIs for four
     specifications (leaked / lenient final / basket+baseline / baseline-only)
     and leave-one-feature-out AUC on the final specification
  3. Calibration: in-the-large gap, Brier, ECE, calibration slope/intercept and
     reliability diagram for class-weighted and unweighted models
  4. Balabit processing: move/drag events, atan2 angular change, velocity from
     client timestamps, declared glitch filter
  5. Friction trigger from the declared tier-to-percentile-band mapping, plus an
     empirical check that the Balabit score and the rank-only score trigger the
     same sessions
  6. Assumption-conditional sensitivity sweep with session bootstrap
  7. Trigger-policy comparison at a matched trigger rate
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (average_precision_score, brier_score_loss,
                             precision_score, recall_score, roc_auc_score)
from sklearn.model_selection import StratifiedKFold, train_test_split

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

HERE = Path(__file__).resolve().parent
CFG = json.loads((HERE / "config.json").read_text())
SEED = CFG["random_seed"]

TARGET = "ordered"
SCOPE = "saw_checkout"
LEAK = "checked_delivery_detail"
BASELINE = ["loc_uk", "returning_user", "device_mobile", "device_computer", "device_tablet"]
BASKET = ["basket_add_detail", "basket_add_list", "basket_icon_click"]
OTHER_EVENTS = ["saw_homepage", "image_picker", "closed_minibasket_click",
                "checked_returns_detail", "list_size_dropdown",
                "promo_banner_click", "sort_by"]
FINAL = BASELINE + BASKET + OTHER_EVENTS
FRICTION_FLAGS = ["closed_minibasket_click", "checked_returns_detail", "sort_by",
                  "list_size_dropdown", "promo_banner_click"]
SPECS = {
    "leaked (final + delivery detail)": FINAL + [LEAK],
    "final, lenient (15 features)": FINAL,
    "baseline + basket (8 features)": BASELINE + BASKET,
    "baseline only (5 features)": BASELINE,
}


# ----------------------------------------------------------------- helpers
def make_model(class_weight):
    return LogisticRegression(class_weight=class_weight, max_iter=2000,
                              random_state=SEED)


def bootstrap_metric(y, p, fn, B, rng):
    n = len(y)
    vals = np.empty(B)
    for b in range(B):
        idx = rng.integers(0, n, n)
        vals[b] = fn(y[idx], p[idx])
    return [float(v) for v in np.quantile(vals, [0.025, 0.975])]


def ece(y, p, bins):
    edges = np.linspace(0, 1, bins + 1)
    ids = np.clip(np.digitize(p, edges[1:-1]), 0, bins - 1)
    total = 0.0
    rows = []
    for k in range(bins):
        m = ids == k
        if m.any():
            gap = abs(p[m].mean() - y[m].mean())
            total += m.mean() * gap
            rows.append((float(p[m].mean()), float(y[m].mean()), int(m.sum())))
    return float(total), rows


def calibration_slope_intercept(y, p):
    eps = 1e-6
    logit = np.log(np.clip(p, eps, 1 - eps) / np.clip(1 - p, eps, 1 - eps))
    m = LogisticRegression(C=1e12, max_iter=1000).fit(logit.reshape(-1, 1), y)
    return float(m.coef_[0, 0]), float(m.intercept_[0])


def oof_scores(X, y, class_weight):
    p = np.zeros(len(y))
    skf = StratifiedKFold(n_splits=CFG["oof_folds"], shuffle=True, random_state=SEED)
    for tr, te in skf.split(X, y):
        p[te] = make_model(class_weight).fit(X[tr], y[tr]).predict_proba(X[te])[:, 1]
    return p


def tex_table(df, path, caption):
    path.write_text(df.to_latex(index=False, escape=True, caption=caption,
                                float_format="%.3f"))


# ----------------------------------------------------------------- stages
def stage_scope_and_lift(df, out):
    scoped = df.loc[df[SCOPE].eq(1)].copy()
    y = scoped[TARGET].to_numpy()
    rows = []
    known = set(FINAL + [LEAK, SCOPE, TARGET])
    for c in scoped.columns:
        if c == TARGET or scoped[c].dtype == object:
            continue
        x = scoped[c]
        if set(pd.unique(x.dropna())) - {0, 1}:
            continue
        m1, m0 = x[y == 1].mean(), x[y == 0].mean()
        rows.append({
            "feature": c,
            "constant_after_scoping": bool(x.nunique() <= 1),
            "prev_converters": m1, "prev_nonconverters": m0,
            "lift": m1 / m0 if m0 > 0 else np.inf,
            "in_register": c in known,
        })
    lift = pd.DataFrame(rows).sort_values("lift", ascending=False)
    lift.to_csv(out / "feature_lift_audit.csv", index=False)
    unaccounted = lift.loc[~lift.in_register & ~lift.constant_after_scoping, "feature"].tolist()
    return scoped, {
        "raw_rows": int(len(df)),
        "raw_conversion_rate": float(df[TARGET].mean()),
        "checkout_rows": int(len(scoped)),
        "checkout_conversion_rate": float(y.mean()),
        "binary_columns_not_in_register": unaccounted,
    }


def stage_discrimination(scoped, out, rng):
    y = scoped[TARGET].to_numpy()
    res, roc_data = {}, {}
    for name, feats in SPECS.items():
        X = scoped[feats].to_numpy(float)
        Xtr, Xva, ytr, yva = train_test_split(X, y, test_size=CFG["validation_fraction"],
                                              random_state=SEED, stratify=y)
        m = make_model(CFG["class_weight"]).fit(Xtr, ytr)
        p = m.predict_proba(Xva)[:, 1]
        yhat = (p >= 0.5).astype(int)
        res[name] = {
            "n_features": len(feats),
            "roc_auc": float(roc_auc_score(yva, p)),
            "roc_auc_ci": bootstrap_metric(yva, p, roc_auc_score, CFG["metric_bootstrap"], rng),
            "pr_auc": float(average_precision_score(yva, p)),
            "pr_auc_ci": bootstrap_metric(yva, p, average_precision_score, CFG["metric_bootstrap"], rng),
            "precision": float(precision_score(yva, yhat, zero_division=0)),
            "recall": float(recall_score(yva, yhat, zero_division=0)),
        }
        roc_data[name] = (yva, p)

    # leave-one-feature-out on the final specification
    Xf = scoped[FINAL].to_numpy(float)
    Xtr, Xva, ytr, yva = train_test_split(Xf, y, test_size=CFG["validation_fraction"],
                                          random_state=SEED, stratify=y)
    base_auc = res["final, lenient (15 features)"]["roc_auc"]
    loo = []
    for j, f in enumerate(FINAL):
        keep = [k for k in range(len(FINAL)) if k != j]
        m = make_model(CFG["class_weight"]).fit(Xtr[:, keep], ytr)
        auc = roc_auc_score(yva, m.predict_proba(Xva[:, keep])[:, 1])
        loo.append({"dropped_feature": f, "roc_auc": auc, "delta_auc": auc - base_auc})
    loo = pd.DataFrame(loo).sort_values("delta_auc")
    loo.to_csv(out / "leave_one_out_auc.csv", index=False)

    tab = pd.DataFrame([{"Specification": k, "Features": v["n_features"],
                         "ROC-AUC": v["roc_auc"],
                         "ROC 95% CI": "[{:.3f}, {:.3f}]".format(*v["roc_auc_ci"]),
                         "PR-AUC": v["pr_auc"], "Precision": v["precision"],
                         "Recall": v["recall"]} for k, v in res.items()])
    tab.to_csv(out / "table_discrimination.csv", index=False)
    tex_table(tab, out / "table_discrimination.tex",
              "Holdout discrimination across availability assumptions")

    fig, ax = plt.subplots(figsize=(5, 4.2))
    from sklearn.metrics import roc_curve
    for name, (yy, pp) in roc_data.items():
        fpr, tpr, _ = roc_curve(yy, pp)
        ax.plot(fpr, tpr, label=f"{name} ({roc_auc_score(yy, pp):.3f})")
    ax.plot([0, 1], [0, 1], "--", color="grey", lw=0.8)
    ax.set_xlabel("False positive rate"); ax.set_ylabel("True positive rate")
    ax.legend(fontsize=7, loc="lower right"); fig.tight_layout()
    fig.savefig(out / "fig_roc_specifications.png", dpi=200); plt.close(fig)
    return res, {"max_single_feature_auc_drop": float(-loo.delta_auc.min()),
                 "feature_with_max_drop": loo.iloc[0].dropped_feature}


def stage_calibration(scoped, out, rng):
    X = scoped[FINAL].to_numpy(float)
    y = scoped[TARGET].to_numpy()
    res, curves = {}, {}
    for label, cw in (("class-weighted", "balanced"), ("unweighted", None)):
        p = oof_scores(X, y, cw)
        e, rows = ece(y, p, CFG["ece_bins"])
        slope, intercept = calibration_slope_intercept(y, p)
        res[label] = {
            "mean_score": float(p.mean()),
            "observed_rate": float(y.mean()),
            "calibration_in_the_large_pp": float(100 * (p.mean() - y.mean())),
            "brier": float(brier_score_loss(y, p)),
            "brier_ci": bootstrap_metric(y, p, brier_score_loss, CFG["metric_bootstrap"], rng),
            "ece": e,
            "calibration_slope": slope,
            "calibration_intercept": intercept,
            "oof_roc_auc": float(roc_auc_score(y, p)),
        }
        curves[label] = (rows, p)
    fig, ax = plt.subplots(figsize=(4.6, 4.2))
    for label, (rows, _) in curves.items():
        xs, ys, ns = zip(*rows)
        ax.plot(xs, ys, "o-", label=f"{label} (ECE {res[label]['ece']:.3f})")
    ax.plot([0, 1], [0, 1], "--", color="grey", lw=0.8)
    ax.set_xlabel("Mean predicted score (bin)"); ax.set_ylabel("Observed conversion (bin)")
    ax.legend(fontsize=8); fig.tight_layout()
    fig.savefig(out / "fig_reliability.png", dpi=200); plt.close(fig)

    # deployment refit coefficients (all scoped data) for the chosen weighting
    m = make_model(CFG["class_weight"]).fit(X, y)
    pd.DataFrame({"feature": FINAL, "coefficient": m.coef_[0]}).assign(
        intercept=m.intercept_[0]).to_csv(out / "deployment_coefficients.csv", index=False)
    chosen = "class-weighted" if CFG["class_weight"] == "balanced" else "unweighted"
    return res, curves[chosen][1]


def stage_balabit(balabit_dir: Path):
    vel, ang, sessions, users = [], [], 0, set()
    vmax = CFG["balabit"]["max_velocity_px_s"]
    for f in sorted(balabit_dir.glob("user*/session_*")):
        d = pd.read_csv(f)
        d = d[d["state"].isin(["Move", "Drag"])]
        t = d["client timestamp"].to_numpy(float)
        x, yy = d["x"].to_numpy(float), d["y"].to_numpy(float)
        dt, dx, dy = np.diff(t), np.diff(x), np.diff(yy)
        dist = np.hypot(dx, dy)
        ok = (dt > 0) & (dist > 0)
        v = dist[ok] / dt[ok]
        ok_v = v <= vmax
        heading = np.arctan2(dy[ok][ok_v], dx[ok][ok_v])
        turn = np.abs(np.angle(np.exp(1j * np.diff(heading))))   # wrapped to [0, pi]
        if len(v[ok_v]) == 0:
            continue
        vel.append(v[ok_v]); ang.append(turn)
        sessions += 1; users.add(f.parent.name)
    vel, ang = np.concatenate(vel), np.concatenate(ang)
    summary = {
        "sessions": sessions, "users": len(users),
        "velocity_mean": float(vel.mean()), "velocity_median": float(np.median(vel)),
        "velocity_p90": float(np.quantile(vel, 0.9)),
        "jitter_mean": float(ang.mean()), "jitter_median": float(np.median(ang)),
        "jitter_p90": float(np.quantile(ang, 0.9)),
        "max_velocity_filter_px_s": vmax,
    }
    return vel, ang, summary


def stage_friction(scoped, vel, ang, rng):
    tiers = scoped[FRICTION_FLAGS].sum(axis=1).to_numpy().astype(int)  # 0..5
    bands = np.array(CFG["tier_percentile_bands"])                      # declared
    lo, hi = bands[tiers, 0], bands[tiers, 1]
    u = lo + (hi - lo) * rng.random(len(tiers))
    q_norm = CFG["normalisation_quantile"]
    vcap, jcap = np.quantile(vel, q_norm), np.quantile(ang, q_norm)
    V = np.clip(np.quantile(vel, u) / vcap, 0, 1)
    J = np.clip(np.quantile(ang, u) / jcap, 0, 1)
    F = CFG["friction_weights"]["jitter"] * J + CFG["friction_weights"]["velocity"] * V
    tq = CFG["trigger_quantile"]
    trig_F = F > np.quantile(F, tq)
    trig_u = u > np.quantile(u, tq)
    return {
        "tiers": tiers, "u": u, "F": F, "trigger": trig_F,
        "check": {
            "trigger_rate": float(trig_F.mean()),
            "agreement_balabit_vs_rank_only": float((trig_F == trig_u).mean()),
            "tier_distribution": {int(k): int(v) for k, v in
                                  zip(*np.unique(tiers, return_counts=True))},
        },
    }


def boot_delta(base, eps_grid, B, rng):
    n = len(base)
    means = np.empty(B)
    for b in range(B):
        means[b] = base[rng.integers(0, n, n)].mean()
    lo, hi = np.quantile(means, [0.025, 0.975])
    return [(e, e * base.mean(), e * lo, e * hi) for e in eps_grid]


def stage_sensitivity(scores, trigger, out, rng):
    base = trigger * (1 - scores)
    rows = boot_delta(base, CFG["assumed_effect_grid"], CFG["bootstrap_resamples"], rng)
    static = scores.mean()
    tab = pd.DataFrame([{"epsilon": e, "static_mean_score_pct": 100 * static,
                         "conditional_mean_score_pct": 100 * (static + d),
                         "score_shift_pp": 100 * d,
                         "ci_low_pp": 100 * l, "ci_high_pp": 100 * h}
                        for e, d, l, h in rows])
    tab.to_csv(out / "table_sensitivity.csv", index=False)
    tex_table(tab, out / "table_sensitivity.tex",
              "Assumption-conditional model-score sensitivity")
    fig, ax = plt.subplots(figsize=(4.8, 3.6))
    ax.plot(tab.epsilon, tab.score_shift_pp, "o-")
    ax.fill_between(tab.epsilon, tab.ci_low_pp, tab.ci_high_pp, alpha=0.3)
    ax.axhline(0, color="grey", lw=0.6)
    ax.set_xlabel(r"Assumed intervention effect $\epsilon$")
    ax.set_ylabel("Mean model-score shift (pp)"); fig.tight_layout()
    fig.savefig(out / "fig_sensitivity.png", dpi=200); plt.close(fig)
    return {"slope_kappa": float(base.mean()), "static_mean_score": float(static)}


def stage_trigger_comparison(scored, scores, friction, out, rng):
    rate = friction["trigger"].mean()
    k = int(round(rate * len(scores)))
    order_low = np.argsort(scores)
    policies = {
        "friction (declared Balabit construction)": friction["trigger"],
        "random at matched rate": rng.random(len(scores)) < rate,
        "lowest model score at matched rate": np.isin(np.arange(len(scores)), order_low[:k]),
        "highest model score at matched rate": np.isin(np.arange(len(scores)), order_low[-k:]),
    }
    # deterministic flags-only rule: smallest tier threshold with rate <= target
    for t in range(6):
        r = (friction["tiers"] >= t).mean()
        if r <= rate + 1e-9:
            policies[f"flags only: tier >= {t} (own rate)"] = friction["tiers"] >= t
            break
    rows = []
    for name, trig in policies.items():
        trig = np.asarray(trig, bool)
        rows.append({
            "policy": name, "trigger_rate": trig.mean(),
            "mean_score_triggered": scores[trig].mean(),
            "mean_headroom_triggered": (1 - scores[trig]).mean(),
            "kappa_slope": (trig * (1 - scores)).mean(),
            "observed_conversion_triggered": scored[TARGET].to_numpy()[trig].mean(),
        })
    tab = pd.DataFrame(rows)
    tab.loc[len(tab)] = {"policy": "all sessions (reference)", "trigger_rate": 1.0,
                         "mean_score_triggered": scores.mean(),
                         "mean_headroom_triggered": (1 - scores).mean(),
                         "kappa_slope": (1 - scores).mean(),
                         "observed_conversion_triggered": scored[TARGET].mean()}
    tab.to_csv(out / "table_trigger_comparison.csv", index=False)
    tex_table(tab, out / "table_trigger_comparison.tex",
              "Headroom targeted by alternative trigger policies")
    return tab.to_dict(orient="records")


# ----------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--smartconvert", required=True)
    ap.add_argument("--balabit", required=True, help="path to training_files/")
    ap.add_argument("--out", default="results")
    a = ap.parse_args()
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(SEED)

    df = pd.read_csv(a.smartconvert)
    scoped, scope = stage_scope_and_lift(df, out)
    disc, loo = stage_discrimination(scoped, out, rng)
    calib, scores = stage_calibration(scoped, out, rng)
    vel, ang, balabit = stage_balabit(Path(a.balabit))
    fr = stage_friction(scoped, vel, ang, rng)
    sens = stage_sensitivity(scores, fr["trigger"], out, rng)
    comp = stage_trigger_comparison(scoped, scores, fr, out, rng)

    results = {"config": CFG, "scope": scope, "discrimination": disc,
               "leave_one_out": loo, "calibration": calib, "balabit": balabit,
               "friction_check": fr["check"], "sensitivity": sens,
               "trigger_comparison": comp}
    (out / "results.json").write_text(json.dumps(results, indent=2, default=float))
    print(json.dumps({k: results[k] for k in
                      ("scope", "leave_one_out", "friction_check", "sensitivity")},
                     indent=2, default=float))


if __name__ == "__main__":
    main()
